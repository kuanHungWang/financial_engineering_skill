"""Hull-White calibration to swaptions (model.calibration + market_data.swaption_vols).

The swaption vols are generated by QuantLib's HullWhite + Jamshidian engine at known (a, sigma), so a
calibration must give those parameters back. The engine wiring is checked by pricing the same trade with
the calibrated model and with the calibrated parameters given explicitly.
Run:  python -m pytest tests -q
"""
import copy
import sys
from pathlib import Path

import pytest
import QuantLib as ql

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT))

from pricer import build_plan, run  # noqa: E402
from pricer import conventions as cv  # noqa: E402
from pricer.market import FlatCurve, SwaptionVolMatrix  # noqa: E402
from pricer.rates import HullWhite, _tenor, calibrate_hull_white, coterminal_points  # noqa: E402

EX = ROOT / "examples"
TODAY = ql.Date(28, 9, 2026)
A, SIG = 0.05, 0.011
EXPIRIES = ["1Y", "2Y", "3Y", "5Y", "7Y"]
TENORS = ["1Y", "3Y", "5Y"]


def flat():
    ql.Settings.instance().evaluationDate = TODAY
    return FlatCurve.build(FlatCurve.Spec(rate=0.04), TODAY)


def hw_vols(vol_type="normal", shift=0.0, a=A, sigma=SIG):
    """ATM swaption vols implied from Hull-White(a, sigma) prices on the flat 4% curve."""
    ts = flat()
    conv = cv.curve_conventions("USD")
    index = conv.ibor_index().clone(ts)
    engine = ql.JamshidianSwaptionEngine(ql.HullWhite(ts, a, sigma))
    qtype = ql.Normal if vol_type == "normal" else ql.ShiftedLognormal
    lo, hi = (1e-6, 0.5) if vol_type == "normal" else (1e-4, 4.0)
    rows = []
    for e in EXPIRIES:
        row = []
        for t in TENORS:
            h = ql.SwaptionHelper(cv.period(e), cv.period(t), ql.QuoteHandle(ql.SimpleQuote(0.01)), index,
                                  ql.Period(conv.fixed_frequency), conv.fixed_day_count, index.dayCounter(), ts,
                                  ql.BlackCalibrationHelper.RelativePriceError, ql.nullDouble(), 1.0, qtype, shift)
            h.setPricingEngine(engine)
            row.append(h.impliedVolatility(h.modelValue(), 1e-12, 1000, lo, hi))
        rows.append(row)
    return {"type": "matrix", "currency": "USD", "vol_type": vol_type, "shift": shift,
            "expiries": EXPIRIES, "tenors": TENORS, "vols": rows}


def matrix(raw):
    return SwaptionVolMatrix.build(SwaptionVolMatrix.Spec.model_validate({k: v for k, v in raw.items() if k != "type"}))


@pytest.mark.parametrize("vol_type,shift", [("normal", 0.0), ("lognormal", 0.0), ("lognormal", 0.02)])
def test_calibration_recovers_mean_reversion_and_volatility(vol_type, shift):
    raw = hw_vols(vol_type, shift)
    vols = matrix(raw)
    a, sigma, fit, rmse = calibrate_hull_white(flat(), vols, vols.quoted, 0.1, 0.005, fix_mean_reversion=False)
    assert a == pytest.approx(A, abs=1e-4)
    assert sigma == pytest.approx(SIG, rel=1e-4)
    assert rmse < 1e-5 and len(fit) == len(EXPIRIES) * len(TENORS)
    assert fit[0]["expiry"] == "1Y" and fit[0]["tenor"] == "1Y"


@pytest.mark.parametrize("error", ["relative_price", "price", "implied_vol"])
def test_calibration_with_fixed_mean_reversion_fits_volatility_only(error):
    vols = matrix(hw_vols())
    pts = [(cv.period("2Y"), cv.period("3Y")), (cv.period("5Y"), cv.period("5Y"))]
    a, sigma, _, rmse = calibrate_hull_white(flat(), vols, pts, A, 0.003, fix_mean_reversion=True, error=error)
    assert a == A
    assert sigma == pytest.approx(SIG, rel=1e-5)
    assert rmse < 1e-7


def test_coterminal_points():
    assert [(_tenor(e), _tenor(t)) for e, t in coterminal_points(5.0)] == \
        [("1Y", "4Y"), ("2Y", "3Y"), ("3Y", "2Y"), ("4Y", "1Y")]
    assert [(_tenor(e), _tenor(t)) for e, t in coterminal_points(1.5)] == [("9M", "9M")]


# ------------------------------------------------------------------ through the engine
def zero_bond_trade(model, market):
    """A trade the model must simulate; its price checks the calibrated parameters reach the simulation."""
    return {"valuation_date": "2026-09-28", "market_data": market, "model": model,
            "observables": {"L6M": {"type": "term_rate", "curve": "USD-FLAT", "tenor": "6M",
                                    "history": {"2026-09-24": 0.04}}},
            "schedules": {"semi": {"type": "generated", "frequency": "6M", "calendar": "NullCalendar"}},
            "trade": {"id": "capped", "maturity": "5Y", "calendar": "NullCalendar", "legs": [
                {"id": "flt", "type": "floating_leg", "index": "L6M", "notional": 100, "schedule": "semi",
                 "cap": 0.045, "day_count": "Actual365Fixed"}]},
            "pricing": {"num_paths": 4000, "seed": 11}}


def market():
    return {"as_of": "2026-09-28", "curves": {"USD-FLAT": {"type": "flat", "rate": 0.04}},
            "swaption_vols": {"SYN": hw_vols()}}


def priced(d):
    plan = build_plan(copy.deepcopy(d), EX)
    assert plan.report.ok, [str(i) for i in plan.report.errors]
    return run(plan)


def test_engine_calibrates_and_simulates_with_the_calibrated_parameters():
    cal = {"type": "hull_white", "discount_curve": "USD-FLAT",
           "calibration": {"swaption_vol": "SYN", "instruments": "all", "calibrate_mean_reversion": True}}
    out = priced(zero_bond_trade(cal, market()))
    diag = out["model_diagnostics"]
    assert diag["mean_reversion"] == pytest.approx(A, abs=1e-4)
    assert diag["volatility"] == pytest.approx(SIG, rel=1e-4)
    assert diag["calibration"]["calibrated"] == ["mean_reversion", "volatility"]
    assert not [w for w in out["warnings"] if "calibration" in w]
    given = {"type": "hull_white", "discount_curve": "USD-FLAT",
             "mean_reversion": diag["mean_reversion"], "volatility": diag["volatility"]}
    assert priced(zero_bond_trade(given, market()))["price"] == pytest.approx(out["price"], rel=1e-12)


def test_engine_coterminal_and_explicit_instruments():
    m = market()
    cot = priced(zero_bond_trade({"type": "hull_white", "discount_curve": "USD-FLAT", "mean_reversion": A,
                                  "calibration": {"swaption_vol": "SYN"}}, m))
    assert [(f["expiry"], f["tenor"]) for f in cot["model_diagnostics"]["calibration"]["instruments"]] == \
        [("1Y", "4Y"), ("2Y", "3Y"), ("3Y", "2Y"), ("4Y", "1Y")]
    # off-grid instruments read interpolated vols; with a = A every HW-generated vol is still fitted closely
    assert cot["model_diagnostics"]["volatility"] == pytest.approx(SIG, rel=2e-2)
    pts = [{"expiry": "2Y", "tenor": "3Y"}, {"expiry": "5Y", "tenor": "5Y"}]
    exp = priced(zero_bond_trade({"type": "hull_white", "discount_curve": "USD-FLAT", "mean_reversion": A,
                                  "calibration": {"swaption_vol": "SYN", "instruments": pts}}, m))
    assert exp["model_diagnostics"]["volatility"] == pytest.approx(SIG, rel=1e-5)


def test_mock_market_example_prices():
    out = priced(__import__("yaml").safe_load((EX / "callable_fixed_rate_bond_calibrated.yaml").read_text()))
    cal = out["model_diagnostics"]["calibration"]
    assert cal["swaption_vol"] == "USD" and len(cal["instruments"]) == 9
