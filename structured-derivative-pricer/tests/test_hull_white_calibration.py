# ------------------------------------------------------------------ validation
def errors(d):
    return {i.path: i.message for i in build_plan(copy.deepcopy(d), EX).report.errors}


def warnings(d):
    return [str(i) for i in build_plan(copy.deepcopy(d), EX).report.warnings]


def test_unknown_swaption_vol_is_reported_with_suggestion():
    e = errors(zero_bond_trade({"type": "hull_white", "discount_curve": "USD-FLAT", "mean_reversion": A,
                                "calibration": {"swaption_vol": "SYNN"}}, market()))
    assert "Did you mean 'SYN'" in e["model.calibration.swaption_vol"]


def test_parameters_are_required_without_calibration():
    e = errors(zero_bond_trade({"type": "hull_white", "discount_curve": "USD-FLAT", "mean_reversion": A}, market()))
    assert any("calibration" in m for m in e.values())
    e = errors(zero_bond_trade({"type": "hull_white", "discount_curve": "USD-FLAT",
                                "calibration": {"swaption_vol": "SYN"}}, market()))
    assert any("calibrate_mean_reversion" in m for m in e.values())


def test_bad_swaption_matrix_is_reported_at_its_path():
    m = market()
    m["swaption_vols"]["SYN"]["vols"] = m["swaption_vols"]["SYN"]["vols"][:-1]
    e = errors(zero_bond_trade({"type": "hull_white", "discount_curve": "USD-FLAT", "mean_reversion": A,
                                "calibration": {"swaption_vol": "SYN"}}, m))
    assert any(p.startswith("market_data.swaption_vols.SYN") and "rows" in msg for p, msg in e.items())
    m = market()
    m["swaption_vols"]["SYN"]["shift"] = 0.01
    assert errors(zero_bond_trade({"type": "hull_white", "discount_curve": "USD-FLAT", "mean_reversion": A,
                                   "calibration": {"swaption_vol": "SYN"}}, m))


def test_short_swaption_coverage_warns():
    m = market()
    m["swaption_vols"]["SYN"].update(expiries=["1Y", "2Y"], tenors=["1Y"],
                                     vols=[[0.008], [0.008]])
    w = warnings(zero_bond_trade({"type": "hull_white", "discount_curve": "USD-FLAT", "mean_reversion": A,
                                  "calibration": {"swaption_vol": "SYN"}}, m))
    assert any("swaption vols cover" in x for x in w)


def test_hull_white_spec_accepts_given_parameters_unchanged():
    spec = HullWhite.Spec(discount_curve="X", mean_reversion=0.03, volatility=0.01)
    assert HullWhite.swaption_vols(spec) == []
